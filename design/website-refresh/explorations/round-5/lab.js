const slug = (value) =>
  value
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/(^-|-$)/g, "");

const inline = (text) => text.replace(/\*([^*]+)\*/g, "<em>$1</em>");

const essayBody = (content) =>
  content.blocks
    .map((block) => {
      const revised = block.rev ? "is-revised" : "";
      const revAttr = block.rev ? ` data-rev="Rev. ${block.rev}"` : "";
      switch (block.type) {
        case "p":
          return `<p class="${revised}"${revAttr}>${block.html}</p>`;
        case "h2":
          return `<h2 id="${slug(block.text)}" class="${revised}"${revAttr}>${block.text}</h2>`;
        case "h3":
          return `<h3 class="${revised}"${revAttr}>${block.text}</h3>`;
        case "emph":
          return `<p class="emph ${revised}"${revAttr}>${block.html}</p>`;
        case "ol":
          return `<ol>${block.items.map((item) => `<li>${item}</li>`).join("")}</ol>`;
        case "ul":
          return `<ul>${block.items.map((item) => `<li>${item}</li>`).join("")}</ul>`;
        case "code":
          return `<pre><code>${block.html}</code></pre>`;
        default:
          return "";
      }
    })
    .join("\n");


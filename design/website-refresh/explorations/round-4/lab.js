function renderTabs() {
  revisionTabs.innerHTML = Object.entries(REVISIONS)
    .map(
      ([key, revision]) =>
        `<button class="lab-tab ${key === state.revision ? "is-active" : ""}" data-revision="${key}" type="button"><span>${revision.number}</span>${revision.label}</button>`,
    )
    .join("");

  viewTabs.innerHTML = Object.entries(VIEWS)
    .map(
      ([key, view]) =>
        `<button class="lab-tab lab-tab-view ${key === state.view ? "is-active" : ""}" data-view="${key}" type="button">${view.label}</button>`,
    )
    .join("");
}

function render() {
  stage.innerHTML = `<div class="proto" data-skin="ash"><div class="page">${VIEWS[state.view].render()}</div></div>`;
  stage.classList.toggle("mobile", state.mobile);
  mobileToggle.classList.toggle("is-active", state.mobile);
  mobileToggle.setAttribute("aria-pressed", String(state.mobile));
  notesBody.innerHTML = notesHTML();
  notesPanel.hidden = !state.notes;
  notesToggle.classList.toggle("is-active", state.notes);
  notesToggle.setAttribute("aria-pressed", String(state.notes));
  document.body.classList.toggle("notes-open", state.notes);
  renderTabs();
  try {
    history.replaceState(null, "", `#${state.view}/${state.revision}`);
  } catch {
    // file:// origins can refuse history updates; the lab still works without them.
  }
}

revisionTabs.addEventListener("click", (event) => {
  const button = event.target.closest("[data-revision]");
  if (!button) return;
  state.revision = button.dataset.revision;
  if (state.view !== "essay") state.view = "essay";
  render();
  window.scrollTo(0, 0);
});

viewTabs.addEventListener("click", (event) => {
  const button = event.target.closest("[data-view]");
  if (!button) return;
  state.view = button.dataset.view;
  render();
});

stage.addEventListener("click", (event) => {
  const link = event.target.closest("[data-goto]");
  if (link) {
    event.preventDefault();
    state.view = link.dataset.goto;
    render();
    window.scrollTo(0, 0);
    return;
  }
  const dead = event.target.closest('a[href="#"]');
  if (dead) event.preventDefault();
});

mobileToggle.addEventListener("click", () => {
  state.mobile = !state.mobile;
  render();
});

notesToggle.addEventListener("click", () => {
  state.notes = !state.notes;
  render();
});

notesClose.addEventListener("click", () => {
  state.notes = false;
  render();
});

function readHash() {
  const [view, revision] = window.location.hash.replace("#", "").split("/");
  if (VIEWS[view]) state.view = view;
  if (REVISIONS[revision]) state.revision = revision;
}

window.addEventListener("hashchange", () => {
  readHash();
  render();
});

readHash();
render();

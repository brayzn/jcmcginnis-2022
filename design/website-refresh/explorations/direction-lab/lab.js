const VIEW_LABELS = {
  home: "Home",
  essay: "Essay",
  archive: "Archive",
  readme: "README",
};

const state = {
  direction: "changelog",
  view: "home",
  mobile: false,
  notes: false,
};

const stage = document.getElementById("stage");
const directionTabs = document.getElementById("direction-tabs");
const viewTabs = document.getElementById("view-tabs");
const notesPanel = document.getElementById("notes-panel");
const notesBody = document.getElementById("notes-body");
const mobileToggle = document.getElementById("mobile-toggle");
const notesToggle = document.getElementById("notes-toggle");
const notesClose = document.getElementById("notes-close");

function notesHTML(key) {
  const direction = DIRECTIONS[key];
  return `
    <p class="notes-direction">${direction.number} · ${direction.name}</p>
    <h2>${direction.thesis}</h2>
    <dl>
      <dt>Signature mechanism</dt><dd>${direction.mechanism}</dd>
      <dt>What it says about you</dt><dd>${direction.says}</dd>
      <dt>Where it might fail</dt><dd>${direction.risk}</dd>
      <dt>Strip the type and color</dt><dd>${direction.strip}</dd>
    </dl>
    <div class="notes-questions">
      <p class="notes-kicker">Ask yourself</p>
      <ul>
        <li>Where did you feel curiosity, recognition, or surprise?</li>
        <li>Did you feel addressed by a person, or presented to by a brand?</li>
        <li>Would this still make sense if the typeface changed?</li>
        <li>Which page did you forget was a prototype?</li>
        <li>What would you still want in five years?</li>
      </ul>
    </div>`;
}

function renderTabs() {
  directionTabs.innerHTML = Object.entries(DIRECTIONS)
    .map(
      ([key, direction]) =>
        `<button class="lab-tab ${key === state.direction ? "is-active" : ""}" data-direction="${key}" type="button"><span>${direction.number}</span>${direction.name}</button>`,
    )
    .join("");

  viewTabs.innerHTML = Object.keys(VIEW_LABELS)
    .map(
      (view) =>
        `<button class="lab-tab lab-tab-view ${view === state.view ? "is-active" : ""}" data-view="${view}" type="button">${VIEW_LABELS[view]}</button>`,
    )
    .join("");
}

function render() {
  stage.innerHTML = DIRECTIONS[state.direction].views[state.view]();
  stage.classList.toggle("mobile", state.mobile);
  mobileToggle.classList.toggle("is-active", state.mobile);
  mobileToggle.setAttribute("aria-pressed", String(state.mobile));
  notesBody.innerHTML = notesHTML(state.direction);
  notesPanel.hidden = !state.notes;
  notesToggle.classList.toggle("is-active", state.notes);
  notesToggle.setAttribute("aria-pressed", String(state.notes));
  document.body.classList.toggle("notes-open", state.notes);
  renderTabs();
  try {
    history.replaceState(null, "", `#${state.direction}/${state.view}`);
  } catch {
    // file:// origins can refuse history updates; the lab still works without them.
  }
}

directionTabs.addEventListener("click", (event) => {
  const button = event.target.closest("[data-direction]");
  if (!button) return;
  state.direction = button.dataset.direction;
  render();
});

viewTabs.addEventListener("click", (event) => {
  const button = event.target.closest("[data-view]");
  if (!button) return;
  state.view = button.dataset.view;
  render();
});

mobileToggle.addEventListener("click", () => {
  state.mobile = !state.mobile;
  render();
});

notesToggle.addEventListener("click", () => {
  state.notes = !state.notes;
  render();
});

notesClose.addEventListener("click", () => {
  state.notes = false;
  render();
});

function readHash() {
  const [direction, view] = window.location.hash.replace("#", "").split("/");
  if (DIRECTIONS[direction]) state.direction = direction;
  if (VIEW_LABELS[view]) state.view = view;
}

window.addEventListener("hashchange", () => {
  readHash();
  render();
});

readHash();
render();

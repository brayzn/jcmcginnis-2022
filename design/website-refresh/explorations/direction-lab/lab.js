const THEMES = ["Ownership", "Trust", "Change", "Work", "Writing", "Memory"];
const SELECTED = ["Directed Chaos", "Organizational Changelog", "Trust First"];

const slug = (value) =>
  value
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/(^-|-$)/g, "");

const essayBody = (content) =>
  content.blocks
    .map((block) => {
      switch (block.type) {
        case "p":
          return `<p>${block.html}</p>`;
        case "h2":
          return `<h2 id="${slug(block.text)}">${block.text}</h2>`;
        case "h3":
          return `<h3>${block.text}</h3>`;
        case "emph":
          return `<p class="emph">${block.html}</p>`;
        case "ol":
          return `<ol class="body-list">${block.items.map((item) => `<li>${item}</li>`).join("")}</ol>`;
        case "ul":
          return `<ul class="body-list">${block.items.map((item) => `<li>${item}</li>`).join("")}</ul>`;
        case "code":
          return `<pre class="body-code"><code>${block.html}</code></pre>`;
        default:
          return "";
      }
    })
    .join("\n");

const byYear = () => {
  const years = [...new Set(site.archive.map((entry) => entry.year))];
  return years.map((year) => ({
    year,
    entries: site.archive.filter((entry) => entry.year === year),
  }));
};

const entriesByTheme = (theme) =>
  site.archive.filter((entry) => entry.themes.includes(theme));

const nav = (items) =>
  items
    .map(
      (item) =>
        `<a class="${item.active ? "active" : ""}" href="#">${item.label}</a>`,
    )
    .join("");

const selectedEntries = () =>
  site.archive.filter((entry) => SELECTED.includes(entry.title));

